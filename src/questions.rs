pub fn build_questions() -> Vec<AxisQuestion> {
    AxisId::ALL
        .iter()
        .enumerate()
        .map(|(axis_index, axis)| AxisQuestion {
            axis: *axis,
            items: EnneagramType::ALL
                .iter()
                .map(|t| QuestionItem {
                    enneagram_type: *t,
                    text: AXIS_TEXTS[axis_index][t.index()].to_string(),
                })
                .collect(),
        })
        .collect()
}
